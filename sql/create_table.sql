CREATE TABLE orders (
    order_id VARCHAR(9) PRIMARY KEY,
    order_date DATE NOT NULL,
    order_hour SMALLINT NOT NULL,
    day_of_week VARCHAR(20) NOT NULL,
    is_weekend SMALLINT NOT NULL,
    is_festival SMALLINT NOT NULL,
    weather VARCHAR(20) NOT NULL,
    pickup_zone VARCHAR(20) NOT NULL,
    dropoff_zone VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(20) NOT NULL,
    rider_experience_years DECIMAL(3,1) NOT NULL,
    rider_rating DECIMAL(2,1) NOT NULL,
    restaurant_rating DECIMAL(2,1) NOT NULL,
    cuisine_type VARCHAR(20) NOT NULL,
    order_items SMALLINT NOT NULL,
    restaurant_load VARCHAR(20) NOT NULL,
    preparation_time_min SMALLINT NOT NULL,
    road_distance_km DECIMAL(6,2) NOT NULL,
    delivery_distance_category VARCHAR(20) NOT NULL,
    traffic_level VARCHAR(20) NOT NULL,
    number_of_signals SMALLINT NOT NULL,
    average_speed_kmph DECIMAL(5,1) NOT NULL,
    delivery_priority VARCHAR(20) NOT NULL,
    time_taken_min SMALLINT NOT NULL
);